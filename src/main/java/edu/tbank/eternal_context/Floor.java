package edu.tbank.eternal_context;

import java.util.Scanner;

/**
 * У Кати насыщенный день на работе. Ей надо передать n разных договоров
 * коллегам. Все встречи происходят на разных этажах, а между этажами можно
 * перемещаться только по лестничным пролетам — считается, что это улучшает
 * физическую форму сотрудников. Прохождение каждого пролета занимает ровно 1
 * минуту.
 * <p>
 * Сейчас Катя на парковочном этаже, планирует свой маршрут. Коллег можно
 * посетить в любом порядке, но один из них покинет офис через <em>t</em> минут.
 * С парковочного этажа лестницы нет — только лифт, на котором можно подняться
 * на любой этаж. В итоге план Кати следующий:
 * <ol>
 *     <li>Подняться на лифте на произвольный этаж. Считается, что лифт поднимается на любой этаж за 0 минут.</li>
 *     <li>Передать всем коллегам договоры, перемещаясь между этажами по лестнице. Считается, что договоры на этаже передаются мгновенно.</li>
 *     <li>В первые t минут передать договор тому коллеге, который планирует уйти.</li>
 *     <li>Пройти минимальное количество лестничных пролетов.</li>
 * </ol>
 * Помогите Кате выполнить все пункты её плана.
 * <h6>Формат входных данных</h6>
 * В первой строке вводятся целые положительные числа <em>n</em> и <em>t</em> — количество сотрудников и время,
 * когда один из сотрудников покинет офис (в минутах). В следующей строке n чисел — номера этажей, на которых находятся сотрудники.
 * Все числа различны и по абсолютной величине не превосходят 100. Номера этажей даны в порядке возрастания.
 * В следующей строке записан номер сотрудника, который уйдёт через t минут.
 * <h6>Формат выходных данных</h6>
 * Выведите одно число — минимально возможное число лестничных пролетов, которое понадобится пройти Кате.
 * <h6>Замечание</h6>
 * В первом примере времени достаточно, чтобы Катя поднялась по этажам по порядку.
 * <p>
 * Во втором примере Кате понадобится подняться к уходящему сотруднику, а потом пройти всех остальных — например, в порядке {1,2,3,4,6}
 * <h6>Примеры данных</h6>
 * <h6>Пример 1</h6>
 * 5 5 <p>
 * 1 4 9 16 25 <p>
 * 2
 */

public class Floor {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);

        // Чтение количества сотрудников и времени t, когда один из сотрудников покинет офис (в минутах)
        int n = scanner.nextInt();
        int t = scanner.nextInt();

        // Чтение номеров этажей
        int[] floors = new int[n];
        for (int i = 0; i < n; i++) {
            floors[i] = scanner.nextInt();
        }

        // Чтение номера сотрудника, который уйдёт через t минут (1-индексация)
        int k = scanner.nextInt();

        int minFloor = floors[0];
        int maxFloor = floors[n - 1];
        int targetFloor = floors[k - 1]; // этаж нужного сотрудника

        // Расстояние от краёв до целевого этажа
        int distFromMin = targetFloor - minFloor;
        int distFromMax = maxFloor - targetFloor;

        // Если можно пройти в один конец, не нарушив дедлайн
        if (distFromMin <= t || distFromMax <= t) {
            System.out.println(maxFloor - minFloor);
        } else {
            // Если нужен разворот, выбираем ближайший край для старта
            int extraSteps = Math.min(distFromMin, distFromMax);
            System.out.println((maxFloor - minFloor) + extraSteps);
        }

        scanner.close();
    }
}
