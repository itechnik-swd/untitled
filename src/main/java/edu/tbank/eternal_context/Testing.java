package edu.tbank.eternal_context;

import java.util.Scanner;


/**
 * Во время разработки некоторой задачи Саша решил сгенерировать несколько новых
 * тестов. Каждый тест Саши должен представлять собой натуральное число, не
 * меньшее <em>l</em> и не большее <em>r</em>. Кроме того, натуральное число в
 * тесте обязательно должно состоять из одинаковых цифр.<p> Например, число 999
 * подходит под это требование, а число 123 — нет. Какое максимальное число
 * различных тестов сможет создать Саша?
 * <h6>Формат входных данных</h6>
 * В единственной строке вводятся два натуральных числа <em>l</em> и <em>r</em>
 * (1 &leq; <em>l</em>,<em>r</em> &leq; 10<sup>18</sup>) — ограничения на тесты
 * Саши.<p> Обратите внимания, что эти числа не вместятся в 32-битный тип
 * данных, используйте 64-битный при необходимости.
 * <h6>Формат выходных данных</h6>
 * Выведите одно число — количество тестов, которое может сделать Саша.
 * <h6>Замечания</h6>
 * В первом тесте Саше подходят номера [4,5,6,7].<p> Во втором тесте подходят
 * все числа, кратные 11, от 11 до 99.
 * <h6>Примеры данных</h6>
 * <h6>Пример 1</h6>
 * Ввод:<p> 4 7<p> Вывод:<p> 4
 * <h6>Пример 2</h6>
 * Ввод:<p> 10 100<p> Вывод:<p> 9
 */
public class Testing {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);

        // Считываем границы диапазона
        long l = scanner.nextLong();
        long r = scanner.nextLong();

        long count = 0;

        // Перебираем длину числа от 1 до 18 знаков
        for (int len = 1; len <= 18; len++) {
            // Формируем базовое число из единиц нужной длины (1, 11, 111, 1111 и т.д.)
            long base = 0;
            for (int i = 0; i < len; i++) {
                base = base * 10 + 1;
            }

            // Умножаем базовое число на цифры от 1 до 9
            for (int digit = 1; digit <= 9; digit++) {
                long currentNum = base * digit;

                // Если число попадает в заданный диапазон, увеличиваем счетчик
                if (currentNum >= l && currentNum <= r) {
                    count++;
                }
            }
        }

        // Выводим результат
        System.out.println(count);
    }
}
