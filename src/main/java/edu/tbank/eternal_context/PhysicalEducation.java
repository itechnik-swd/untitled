package edu.tbank.eternal_context;

import java.util.ArrayList;
import java.util.List;
import java.util.Scanner;

/**
 * На физкультуре происходит разбиение по двум командам. Ребята выстроены в
 * шеренгу, у каждого из них есть свой рост a<sub>i</sub>. Разбиение по командам
 * произойдет по принципу «чётный-нёчетный» — все школьники с чётным ростом
 * отправляются в одну команду, а нечётные — в другую.<p> В отличие от
 * привычного урока, ребята не выстроились по росту. Вместо привычного порядка
 * они встали случайно. Теперь физрук Яша смотрит на шеренгу и думает — может ли
 * <b>ровно</b> одна пара учеников поменяться местами так, чтобы команды
 * оказались такими же, как и по принципу «первый-второй». Иначе говоря, он
 * хочет получить такой порядок, при котором все ученики с чётным ростом стоят
 * на чётных позициях, а с нечётным — на нечётных.<p> Помогите Яше найти нужную
 * замену.
 * <h6>Формат входных данных</h6>
 * В первой строке находится число <em>n</em>(2 ≤ n ≤ 1000) — количество
 * учеников в шеренге.<p> В следующей строке находится <em>n</em> натуральных
 * чисел a<sub>i</sub>(1 ≤ a<sub>i</sub> ≤ 10<sup>9</sup>) — рост учеников.
 * <h6>Формат выходных данных</h6>
 * В единственной строке выведите <em>i</em> и <em>j</em> — номера элементов,
 * которые нужно поменять местами, чтобы добиться заданного условия (1 ≤ i,j ≤
 * n,i ≠ j). Если ответов несколько — разрешается вывести любой. Если не
 * существует способа поменять два элемента местами — выведите -1 -1.
 * <h6>Замечания</h6>
 * В первом примере хотя бы один ученик с чётным ростом будет стоять на нечётной
 * позиции. Во втором тесте замена приведёт к неправильному состоянию.<p> В
 * третьем тесте из условия замена приведет шеренгу к валидному состоянию
 * [1,2].
 * <h6>Примеры данных</h6>
 * <h6>Пример 1</h6>
 * Ввод:<p> 4<p> 2 1 4 6<p> Вывод:<p> -1 -1
 * <h6>Пример 2</h6>
 * Ввод:<p> 2<p> 1 2<p> Вывод:<p> -1 -1
 * <h6>Пример 3</h6>
 * Ввод:<p> 2<p> 2 1<p> Вывод:<p> 1 2
 */

public class PhysicalEducation {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        int n = scanner.nextInt(); // количество учеников в шеренге

        // Списки для хранения индексов "неправильных" позиций
        List<Integer> badOdd = new ArrayList<>();
        List<Integer> badEven = new ArrayList<>();

        for (int i = 1; i <= n; i++) {
            int height = scanner.nextInt();

            if (i % 2 != 0 && height % 2 == 0) {
                // Нечетная позиция, но четный рост
                badOdd.add(i);
            } else if (i % 2 == 0 && height % 2 != 0) {
                // Четная позиция, но нечетный рост
                badEven.add(i);
            }
        }

        // Анализируем результаты
        if (badOdd.size() == 1 && badEven.size() == 1) {
            // Нашли ровно одну пару для перестановки
            System.out.println(badOdd.get(0) + " " + badEven.get(0));
        } else if (badOdd.isEmpty() && badEven.isEmpty()) {
            // Шеренга уже построена правильно
            if (n >= 3) {
                // Можно поменять местами любые два элемента одной четности (например, 1 и 3)
                System.out.println("1 3");
            } else {
                // Если n = 2, любую пару замена испортит
                System.out.println("-1 -1");
            }
        } else {
            // В любых других случаях одной заменой не обойтись
            System.out.println("-1 -1");
        }
    }
}
